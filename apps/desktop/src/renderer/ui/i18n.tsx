const dictionaries: Record<AppLocale, TranslationDictionary> = { "pt-BR": ptBR, en };

interface I18nValue {
  readonly locale: AppLocale;
  readonly setLocale: (locale: AppLocale) => Promise<void>;
  readonly t: (key: TranslationKey, values?: Readonly<Record<string, string | number>>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider(props: {
  readonly children: ReactNode;
  readonly locale: AppLocale;
  readonly onLocaleChange: (locale: AppLocale) => Promise<void>;
}) {
  useEffect(() => {
    document.documentElement.lang = props.locale;
  }, [props.locale]);

  const t: I18nValue["t"] = (key, values = {}) =>
    Object.entries(values).reduce(
      (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
      dictionaries[props.locale][key]
    );

  return (
    <I18nContext.Provider value={{ locale: props.locale, setLocale: props.onLocaleChange, t }}>
      {props.children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (value === null) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return value;
}

